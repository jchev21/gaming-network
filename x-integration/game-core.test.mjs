import assert from 'node:assert/strict';
import { createLobby, finalizeLobby, joinLobby, publicLobby } from './game-core.mjs';
const t=100000;
const config={game:'arcade-runner',platform:'web',mode:'first',seats:5,roundSeconds:60,title:'Test Round'};
const g=createLobby(config,'1001',t,'game-A');
assert.equal(g.status,'open');
for(let i=1;i<=5;i++) joinLobby(g,String(1001+i),'Player '+i,t+100+i);
assert.equal(g.status,'ready');
assert.equal(publicLobby(g).confirmedCount,5);
assert.deepEqual(publicLobby(g).entries.map(x=>x.selected),Array(5).fill(true));
assert.throws(()=>joinLobby(g,'12345','Late',t+10000),e=>e.code==='CLOSED');
const second=createLobby({...config,seats:2},'101',t,'game-B');
joinLobby(second,'102','first',t);
assert.throws(()=>joinLobby(second,'102','again',t+2),e=>e.code==='DUPLICATE');
assert.throws(()=>joinLobby(second,'not-an-id','bad',t+2),e=>e.code==='AUTH_REQUIRED');
joinLobby(second,'103','second',t+3); assert.equal(second.status,'ready');
const lottery=createLobby({...config,mode:'lottery'},'100',t,'lottery-A');
for(let i=0;i<20;i++)joinLobby(lottery,String(i+2000),'entrant '+i,t+200+i);
assert.equal(publicLobby(lottery,t+20000).status,'open');
assert.throws(()=>joinLobby(lottery,'2000','repeat',t+1000),e=>e.code==='DUPLICATE');
finalizeLobby(lottery,t+299999,()=>0);assert.equal(lottery.status,'open');
finalizeLobby(lottery,t+300000,()=>0);assert.equal(lottery.status,'ready');
assert.equal(lottery.winners.length,5);
assert.equal(new Set(lottery.winners).size,5);
assert.equal(publicLobby(lottery).entries.length,20);
assert.ok(!JSON.stringify(publicLobby(lottery)).includes('ownerXId'));
assert.ok(!JSON.stringify(publicLobby(lottery)).includes('"xId"'));
assert.deepEqual(finalizeLobby(lottery,t+600000).winners,lottery.winners);
assert.throws(()=>createLobby({...config,roundSeconds:11},'1',t),e=>e.code==='INVALID_ROUND');
for (const hosted of ['fortnite','warzone','apex-legends','rocket-league','minecraft','roblox','valorant','custom-multiplayer']) {
  const round=createLobby({...config,game:hosted,platform:'pc'},'1',t);
  assert.equal(round.game,hosted);
  assert.equal(round.status,'open');
}
assert.throws(()=>createLobby({...config,game:'fake'},'1',t),e=>e.code==='INVALID_GAME');
const exp=createLobby(config,'100',t,'expire');
finalizeLobby(exp,t+300001);assert.equal(exp.status,'closed');
assert.throws(()=>joinLobby(exp,'109','late',t+300001),e=>e.code==='CLOSED');
const hosted=createLobby({...config,game:'fortnite',platform:'pc',host:{mode:'Duos',region:'na-east',crossplay:'on',islandCode:'1234-5678-9012'}},'100',t);
assert.equal(publicLobby(hosted).host.islandCode,'1234-5678-9012');
assert.equal(publicLobby(hosted).host.region,'na-east');
assert.ok(!JSON.stringify(publicLobby(hosted)).includes('ownerXId'));
assert.throws(()=>createLobby({...config,game:'warzone',host:{region:'invalid'}},'100',t),e=>e.code==='INVALID_REGION');
assert.throws(()=>createLobby({...config,game:'warzone',host:{islandCode:'1234-5678-9012'}},'100',t),e=>e.code==='INVALID_ISLAND');
console.log('Game core tests passed: first-come, five-minute lottery, identity, limits, privacy, finalization');